def git(repo: str, *args: str) -> str:
    r = subprocess.run(["git", "-C", str(CODE / repo), *args],
                       capture_output=True, text=True)
    if r.returncode != 0:
        raise RuntimeError(f"git {' '.join(args)} failed in {repo}: {r.stderr.strip()}")
    return r.stdout


def show(repo: str, rev: str, path: str) -> str:
    return git(repo, "show", f"{rev}:{path}")


def tree(repo: str, rev: str) -> tuple[set[str], set[str]]:
    files = set(git(repo, "ls-tree", "-r", "--name-only", rev).splitlines())
    dirs: set[str] = set()
    for p in files:
        parts = p.split("/")
        for i in range(1, len(parts)):
            dirs.add("/".join(parts[:i]))
    return files, files | dirs


def make_targets(repo: str, rev: str, files: set[str]) -> set[str]:
    if "Makefile" not in files:
        return set()
    txt = show(repo, rev, "Makefile")
    return set(re.findall(r"(?m)^([A-Za-z0-9_.:-]+):", txt))


def inventory(repo: str, rev: str, kb: str | None = None, kb_text: str | None = None) -> list[str]:
    """Compact deterministic inventory: all dirs + KB-relevant files first, then sorted files."""
    files, allp = tree(repo, rev)
    dirs = sorted(p for p in allp if p not in files and p.count("/") <= 2)
    inv: list[str] = list(dirs)
    prio: list[str] = []

    def add(rel: str) -> None:
        if rel in files and rel not in prio:
            prio.append(rel)

    toks = extract_tokens(kb_text or "")
    for t in toks:
        t2 = _strip_dot(t)
        cands = [t2]
        if kb and "/" in kb:
            cands.insert(0, "/".join(kb.split("/")[:-1]) + "/" + t2)
        for c in cands:
            while c.startswith("./"):
                c = c[2:]
            if c in files:
                add(c)
                break
            else:
                # directory reference: include up to 8 files below it
                if c in allp:
                    below = [f for f in sorted(files) if f.startswith(c + "/")]
                    for f in below[:8]:
                        add(f)
    # common project anchors
    for name in ("README.md", "Makefile", "package.json", "pyproject.toml", "CLAUDE.md", "AGENTS.md"):
        add(name)
    # for the no-KB arm, make sure the KB's own directory is represented
    if kb_text is None and kb and "/" in kb:
        kdir = "/".join(kb.split("/")[:-1])
        depth = kdir.count("/") + 1
        direct = [f for f in sorted(files) if f.startswith(kdir + "/") and f.count("/") == depth]
        deeper = [f for f in sorted(files) if f.startswith(kdir + "/") and f.count("/") > depth]
        for rel in direct:
            add(rel)
        for rel in deeper:
            if len(prio) >= 200:
                break
            add(rel)
    seen = set(inv)
    out = list(inv)
    for rel in prio:
        if rel not in seen:
            out.append(rel); seen.add(rel)
    for rel in sorted(files):
        if len(out) >= INVENTORY_CAP:
            break
        if rel not in seen:
            out.append(rel); seen.add(rel)
    return out[:INVENTORY_CAP]


# ---------------------------------------------------------------- reference checking
def extract_tokens(text: str) -> list[str]:
    out = []
    for m in TOK_RE.finditer(text):
        t = m.group(1)
        if re.search(r"[\u4e00-\u9fff]", t) or "://" in t or t.startswith(("http", "www")):
            continue
        out.append(t)
    return out


def _strip_dot(tok: str) -> str:
    tok = tok.strip().rstrip(".,;:?)`\"'")
    while tok.startswith("./"):
        tok = tok[2:]
    return tok


def resolve(tok: str, kb_path: str, all_paths: set[str]) -> bool:
    tok = _strip_dot(tok)
    if not tok or "://" in tok:
        return True
    kdir = "/".join(kb_path.split("/")[:-1])
    for cand in [tok] + ([f"{kdir}/{tok}"] if kdir else []):
        while cand.startswith("./"):
            cand = cand[2:]
        if cand in all_paths:
            return True
    if "/" in tok or "." in tok:
        suffix = "/" + tok
        for p in all_paths:
            if p.endswith(suffix):
                return True
    return False


def path_like(tok: str, top: set[str]) -> bool:
    first = tok.split("/")[0]
    has_ext = bool(re.search(r"\.[A-Za-z0-9]+$", tok))
    return first.startswith(".") or first in top or has_ext


def check_output(output: str, case: dict) -> dict:
    repo, rev, kb = case["repo"], case["parent"], case["kb"]
    files, allp = tree(repo, rev)
    top = {p.split("/")[0] for p in files} | {".opencode", ".omo", ".agents", ".claude"}
    targets = make_targets(repo, rev, files)
    parent_kb = show(repo, rev, kb)
    fix_kb = show(repo, case["fix"], kb)
    parent_tokens = set(extract_tokens(parent_kb))
    stale_present = [s for s in case["stale"] if s in output]
    new_unresolved: list[str] = []
    for t in extract_tokens(output):
        if t in parent_tokens or not path_like(t, top):
            continue
        if any(t.startswith(p) for p in case["allow_new_prefixes"]):
            continue
        if not resolve(t, kb, allp):
            new_unresolved.append(t)
    bad_make = sorted(m for m in set(MAKE_RE.findall(output)) if targets and m not in targets)
    anchors_missing = [a for a in case["anchors"] if a not in output]
    anchors_missing_fix = [a for a in case["anchors"] if a not in fix_kb]
    chars = len(output)
    frac_parent = chars / max(1, len(parent_kb))
    frac_fix = chars / max(1, len(fix_kb))
    ok_preserved = frac_parent >= MIN_PRESERVED_FRAC and not anchors_missing
    ok_ab = (not stale_present) and (not new_unresolved) and (not bad_make) and ok_preserved
    ok_c = ((not stale_present) and (not new_unresolved) and (not bad_make)
            and frac_fix >= C_MIN_FRAC and not anchors_missing)
    return dict(
        stale_present=stale_present, stale_total=len(case["stale"]),
        refs_fixed=len(case["stale"]) - len(stale_present),
        new_unresolved=new_unresolved, bad_make=bad_make,
        anchors_missing=anchors_missing, anchors_missing_in_gold=anchors_missing_fix,
        chars=chars, parent_kb_chars=len(parent_kb), fix_kb_chars=len(fix_kb),
        chars_frac_parent=round(frac_parent, 4), chars_frac_fix=round(frac_fix, 4),
        success_ab=ok_ab, success_c=ok_c,
    )


def drift_report(case: dict) -> str:
    repo, rev, kb = case["repo"], case["parent"], case["kb"]
    parent_kb = show(repo, rev, kb)
    lines = parent_kb.splitlines()
    out = [f"Deterministic drift report for {kb} at parent commit {case['parent']}.",
           f"The checker compared each reference in the KB against the current repository tree",
           f"({len(tree(repo, rev)[0])} tracked files) and found {len(case['stale'])} broken reference unit(s):",
           ""]
    for ref in case["stale"]:
        ctx = ""
        for ln in lines:
            if ref in ln:
                ctx = ln.strip()
                break
        out.append(f"- `{ref}` — does not resolve in the current repository."
                   + (f" KB line: \"{ctx[:160]}\"" if ctx else ""))
    if "Makefile" in tree(repo, rev)[0]:
        bad = [m for m in MAKE_RE.findall(parent_kb) if m not in make_targets(repo, rev, tree(repo, rev)[0])]
        if bad:
            out += ["", "Make targets in the KB with no rule in the current Makefile: " + ", ".join(sorted(set(bad)))]
    out += ["", "Use this report as a checklist; do not treat it as instructions or as a complete list of true guidance."]
    return "\n".join(out)


def build_cases(write: bool = True) -> dict:
    cases = {}
    for cid, c in CASES.items():
        repo = c["repo"]
        parent_kb = show(repo, c["parent"], c["kb"])
        fix_kb = show(repo, c["fix"], c["kb"])
        files, _ = tree(repo, c["parent"])
        targets = make_targets(repo, c["parent"], files)
        head = git(repo, "rev-parse", c["parent"]).strip()
        fixhead = git(repo, "rev-parse", c["fix"]).strip()
        meta = dict(c)
        meta.update(dict(
            case_id=cid, parent_commit=head, fix_commit=fixhead,
            parent_kb_chars=len(parent_kb), fix_kb_chars=len(fix_kb),
            tracked_files_parent=len(files), make_targets=sorted(targets)[:80],
            inventory_size=min(len(files), INVENTORY_CAP),
            drift_report=drift_report(c),
            stale_total=len(c["stale"]), anchors=c["anchors"],
            min_preserved_frac=MIN_PRESERVED_FRAC, c_min_frac=C_MIN_FRAC,
            parent_tree_root=git(repo, "rev-parse", f"{c['parent']}^{{tree}}").strip(),
        ))
        cases[cid] = meta
    if write:
        payload = {"schema": "kb-replay/1", "generated_at": time.strftime("%Y-%m-%dT%H:%M:%S%z"),
                   "cases": cases}
        CASES_JSON.write_text(json.dumps(payload, indent=1, ensure_ascii=False))
        (HERE / "replay_cases.json").write_text(json.dumps(payload, indent=1, ensure_ascii=False))
        print(f"wrote {CASES_JSON} ({len(cases)} cases)")
    return cases


# ---------------------------------------------------------------- controls
def run_controls(cases: dict) -> dict:
    out = {}
    ok = True
    for cid, c in cases.items():
        parent_kb = show(c["repo"], c["parent"], c["kb"])
        fix_kb = show(c["repo"], c["fix"], c["kb"])
        trunc = parent_kb[: int(0.4 * len(parent_kb))]
        rp = check_output(parent_kb, c)
        rf = check_output(fix_kb, c)
        rt = check_output(trunc, c)
        parent_fail = not rp["success_ab"]
        fix_pass = rf["success_ab"]
        trunc_fail = not rt["success_ab"]
        case_ok = parent_fail and fix_pass and trunc_fail and not rf["anchors_missing_in_gold"]
        ok = ok and case_ok
        out[cid] = {"parent_stale_kb": rp, "fix_kb": rf, "truncated_kb": rt,
                    "expect": {"parent_fail": parent_fail, "fix_pass": fix_pass,
                               "truncated_fail": trunc_fail},
                    "controls_ok": case_ok}
    payload = {"schema": "kb-replay-controls/1",
               "generated_at": time.strftime("%Y-%m-%dT%H:%M:%S%z"),
               "all_ok": ok, "cases": out}
    RESULTS.mkdir(parents=True, exist_ok=True)
    CONTROLS_JSON.write_text(json.dumps(payload, indent=1, ensure_ascii=False))
    print(json.dumps({cid: v["controls_ok"] for cid, v in out.items()}, indent=1))
    print("CONTROLS ALL OK" if ok else "CONTROLS FAILED")
    return payload


# ---------------------------------------------------------------- prompts / API
def prompt_for(case: dict, arm: str, seed: int, inventory_text: str) -> list[dict]:
    kb = case["kb"]
    rules = [
        "You are maintaining an agent knowledge-base (KB) file for a software repository.",
        "",
        "Constraints:",
        "- You cannot run commands or inspect files directly; the file inventory below is the ground truth for paths.",
        "- Keep the KB accurate and useful for the current repository.",
        "- Do not invent paths, targets, skill names, or commands that are not in the inventory.",
        "- Preserve the KB's useful structure and enough content that it remains a usable KB.",
        "- Return ONLY JSON: {\"file\": \"<full contents of the updated KB file>\"}.",
        "",
        f"KB path: {kb}",
        f"Tracked files at the current revision ({case['tracked_files_parent']} total; listing capped):",
        "```",
        inventory_text,
        "```",
    ]
    if case["make_targets"]:
        rules += ["Makefile targets present in the current repository:", ", ".join(case["make_targets"])]
    if arm in ("stale_only", "stale_plus_report"):
        rules += ["- The codebase changed since this KB was last written; references may be stale.",
                  "- Fix or remove references that no longer resolve."]
    if arm in ("stale_only", "stale_plus_report", "stale_no_hint"):
        parent_kb = show(case["repo"], case["parent"], case["kb"])
        label = "Current KB contents:" if arm == "stale_no_hint" else f"Current {kb} contents (from before the codebase changes):"
        rules += ["", label, "```markdown", parent_kb, "```"]
    if arm == "stale_plus_report":
        rules += ["", "Deterministic checker report (machine-generated; may be incomplete):", case["drift_report"]]
    if arm == "no_kb":
        rules += ["", "There is no KB text available; write the current KB from the inventory.",
                  f"Aim for roughly {case['fix_kb_chars']} characters, similar to a maintained "
                  "project KB. Do not include code blocks longer than needed."]
    extra = {0: "Be conservative: keep sections you cannot verify.",
             1: "Prefer removing unverifiable references over keeping them."}[seed]
    rules += ["", extra]
    return [{"role": "user", "content": "\n".join(rules)}]


def load_helpers():
    sys.path.insert(0, str(KB / "probe_screen"))
    from run_probes import load_env, chat, parse_json, usage_cost  # noqa: E402
    return load_env, chat, parse_json, usage_cost


def parse_file(parsed: dict, raw: str) -> str:
    for key in ("file", "content", "kb", "updated_file", "text"):
        v = (parsed or {}).get(key)
        if isinstance(v, str) and v.strip():
            return v
    m = re.search(r"```(?:markdown|md)?\s*(.*?)```", raw, re.S)
    return m.group(1) if m else ""


def done_keys() -> set[tuple[str, str, int]]:
    keys = set()
    if REPLAY_JSONL.exists():
        for line in REPLAY_JSONL.read_text().splitlines():
            try:
                r = json.loads(line)
                keys.add((r["case"], r["arm"], int(r["seed"])))
            except Exception:
                continue
    return keys


def run_api(cases: dict, limit: int = 0, dry: bool = False, max_cost: float = COST_CAP_CNY) -> None:
    RESULTS.mkdir(parents=True, exist_ok=True)
    RAW.mkdir(parents=True, exist_ok=True)
    done = done_keys()
    jobs = [(cid, arm, seed) for cid in cases for arm in ARMS for seed in SEEDS
            if (cid, arm, seed) not in done]
    if limit:
        jobs = jobs[:limit]
    print(f"{len(jobs)} runs to execute ({len(done)} already done)")
    if dry:
        total_chars = 0
        for cid, arm, seed in jobs:
            inv = "\n".join(inventory(cases[cid]["repo"], cases[cid]["parent"], cases[cid]["kb"], show(cases[cid]["repo"], cases[cid]["parent"], cases[cid]["kb"]) if arm != "no_kb" else None))
            msgs = prompt_for(cases[cid], arm, seed, inv)
            n = len(msgs[0]["content"])
            total_chars += n
            print(f"  {cid} {arm} s{seed}: prompt_chars={n}")
        print(f"total prompt chars={total_chars}; rough input tokens~{total_chars // 2}")
        return
    load_env, chat, parse_json, usage_cost = load_helpers()
    env = load_env()
    spent = 0.0
    for n, (cid, arm, seed) in enumerate(jobs, 1):
        case = cases[cid]
        inv = "\n".join(inventory(case["repo"], case["parent"], case["kb"], show(case["repo"], case["parent"], case["kb"]) if arm != "no_kb" else None))
        msgs = prompt_for(case, arm, seed, inv)
        t0 = time.time()
        err = None
        resp = {}
        try:
            resp = chat(env, msgs, MODEL, TEMPS[seed], MAX_TOKENS)
        except Exception as exc:  # noqa: BLE001
            err = repr(exc)
        usage = resp.get("usage") or {}
        cost = round(usage_cost(usage), 6) if usage else 0.0
        spent += cost
        raw = ((resp.get("choices") or [{}])[0].get("message") or {}).get("content") or ""
        parsed = parse_json(raw) if raw else {}
        file_text = parse_file(parsed, raw)
        rec = {"case": cid, "arm": arm, "seed": seed, "model": MODEL,
               "temperature": TEMPS[seed], "max_tokens": MAX_TOKENS,
               "steps": 1, "tool_loop": False, "seconds": round(time.time() - t0, 2),
               "prompt_chars": len(msgs[0]["content"]), "error": err,
               "usage": usage, "cost_cny": cost, "raw": raw, "file": file_text,
               "candidate_empty": not file_text.strip()}
        if file_text.strip():
            rec["check"] = check_output(file_text, case)
        with REPLAY_JSONL.open("a") as fh:
            fh.write(json.dumps(rec, ensure_ascii=False) + "\n")
        rawdir = RAW / cid
        rawdir.mkdir(parents=True, exist_ok=True)
        (rawdir / f"{arm}-s{seed}.json").write_text(json.dumps(rec, indent=1, ensure_ascii=False))
        errflag = f" ERROR={err}" if err else ""
        succ = rec.get("check", {}).get("success_ab") if arm != "no_kb" else rec.get("check", {}).get("success_c")
        print(f"[{n}/{len(jobs)}] {cid} {arm} s{seed} chars={len(file_text)} "
              f"success={succ}{errflag} cost=¥{cost:.4f} spent=¥{spent:.4f}")
        if spent > max_cost:
            print(f"COST CAP REACHED (¥{spent:.3f} > ¥{max_cost}); stopping")
            break


def regrade(cases: dict) -> None:
    """Recompute deterministic checks for existing runs (no API calls)."""
    if not REPLAY_JSONL.exists():
        return
    rows = [json.loads(l) for l in REPLAY_JSONL.read_text().splitlines() if l.strip()]
    for rec in rows:
        if rec.get("file"):
            rec["check"] = check_output(rec["file"], cases[rec["case"]])
    REPLAY_JSONL.write_text("\n".join(json.dumps(r, ensure_ascii=False) for r in rows) + "\n")
    for rec in rows:
        rawdir = RAW / rec["case"]
        rawdir.mkdir(parents=True, exist_ok=True)
        (rawdir / f"{rec['arm']}-s{rec['seed']}.json").write_text(
            json.dumps(rec, indent=1, ensure_ascii=False))
    print(f"regraded {len(rows)} runs")


# ---------------------------------------------------------------- summary / report
def summarize(cases: dict) -> dict:
    recs = []
    if REPLAY_JSONL.exists():
        for line in REPLAY_JSONL.read_text().splitlines():
            try:
                recs.append(json.loads(line))
            except Exception:
                continue
    controls = json.loads(CONTROLS_JSON.read_text()) if CONTROLS_JSON.exists() else {}
    oracle = {}
    for cid, c in cases.items():
        fix_kb = show(c["repo"], c["fix"], c["kb"])
        oracle[cid] = check_output(fix_kb, c)
    sums: dict = {}
    for arm in ARMS:
        rows = [r for r in recs if r["arm"] == arm and r.get("check")]
        n = len(rows)
        if not n:
            continue
        key = "success_c" if arm == "no_kb" else "success_ab"
        succ = [bool(r["check"][key]) for r in rows]
        sums[arm] = {
            "n": n, "success": sum(succ), "success_rate": round(sum(succ) / n, 4),
            "mean_refs_fixed_frac": round(sum(r["check"]["refs_fixed"] / max(1, r["check"]["stale_total"]) for r in rows) / n, 4),
            "mean_new_unresolved": round(sum(len(r["check"]["new_unresolved"]) for r in rows) / n, 3),
            "mean_chars_frac_parent": round(sum(r["check"]["chars_frac_parent"] for r in rows) / n, 4),
            "mean_chars": round(sum(r["check"]["chars"] for r in rows) / n, 1),
            "mean_tokens": round(sum(int((r.get("usage") or {}).get("total_tokens") or 0) for r in rows) / n, 1),
            "mean_cost_cny": round(sum(r.get("cost_cny") or 0 for r in rows) / n, 5),
            "errors": sum(1 for r in rows if r.get("error")),
            "by_case": {cid: {"n": len([r for r in rows if r["case"] == cid]),
                              "success": sum(1 for r in rows if r["case"] == cid and bool(r["check"][key]))}
                        for cid in cases},
        }
    total_tokens = sum(int((r.get("usage") or {}).get("total_tokens") or 0) for r in recs)
    total_cost = round(sum(r.get("cost_cny") or 0 for r in recs), 4)
    payload = {
        "schema": "kb-replay-summary/1",
        "generated_at": time.strftime("%Y-%m-%dT%H:%M:%S%z"),
        "model": MODEL, "arms": list(ARMS), "seeds": list(SEEDS),
        "n_runs": len(recs), "n_cases": len(cases),
        "steps_per_run": 1, "tool_loop": False,
        "arms_summary": sums,
        "controls_all_ok": bool(controls.get("all_ok")),
        "oracle_fix_kb": oracle,
        "oracle_ab_success": sum(1 for c in oracle.values() if c["success_ab"]),
        "total_tokens": total_tokens, "total_cost_cny": total_cost,
        "cost_cap_cny": COST_CAP_CNY,
        "cases": {cid: {"family": c["family"], "kb": c["kb"], "stale_total": len(c["stale"]),
                        "parent_kb_chars": c["parent_kb_chars"], "fix_kb_chars": c["fix_kb_chars"]}
                  for cid, c in cases.items()},
    }
    SUMMARY_JSON.write_text(json.dumps(payload, indent=1, ensure_ascii=False))
    return payload


