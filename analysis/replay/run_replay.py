# ---------------------------------------------------------------- main
def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--build-cases", action="store_true")
    ap.add_argument("--controls", action="store_true")
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--run", action="store_true")
    ap.add_argument("--summary", action="store_true")
    ap.add_argument("--regrade", action="store_true")
    ap.add_argument("--limit", type=int, default=0)
    ap.add_argument("--max-cost", type=float, default=COST_CAP_CNY)
    args = ap.parse_args()
    if args.build_cases:
        build_cases()
    cases = json.loads(CASES_JSON.read_text())["cases"] if CASES_JSON.exists() else build_cases()
    if args.controls:
        run_controls(cases)
    if args.dry_run:
        run_api(cases, limit=args.limit, dry=True, max_cost=args.max_cost)
    if args.run:
        rec = json.loads(CONTROLS_JSON.read_text()) if CONTROLS_JSON.exists() else run_controls(cases)
        if not rec.get("all_ok"):
            print("controls not green; refusing API calls")
            return 2
        run_api(cases, limit=args.limit, max_cost=args.max_cost)
    if args.regrade:
        regrade(cases)
    if args.summary:
        summary = summarize(cases)
        write_report(cases, summary)
        print(json.dumps({a: {k: v for k, v in s.items() if k in ("n", "success", "success_rate")}
                          for a, s in summary["arms_summary"].items()}, indent=1))
        print(f"total cost ¥{summary['total_cost_cny']:.4f}, tokens {summary['total_tokens']}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
