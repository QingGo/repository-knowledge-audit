#!/usr/bin/env python3
"""Real-repo replay pilot: can an LLM repair visible reference drift in an agent KB?

Single-turn, no tool loop: the model receives the parent-commit KB (arms A/B), a deterministic
file inventory, and for arm B a deterministic drift report generated by this script's checker.
Arm C gets no KB text and must write the KB from the inventory. Grading is deterministic reference
checking against the parent commit tree (paths, make targets). No LLM judge.

Usage:
  python3 run_replay.py --build-cases     # writes cases.json + replay_cases.json
  python3 run_replay.py --controls        # writes results/controls.json (must pass before API)
  python3 run_replay.py --dry-run         # prompt sizes / cost estimate, no API calls
  python3 run_replay.py --run             # executes missing (case, arm, seed) runs; resume-safe
  python3 run_replay.py --summary         # writes results/summary.json + REPORT.md
"""
